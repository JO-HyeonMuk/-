#include <string>
#include <vector>

using namespace std;

int solution(int n) {
    int answer = 0;
    int sqr = 1; // 3의 거듭제곱을 저장할 변수 (3^0 = 1부터 시작)
    vector<int> a; // 3진법 자리수들을 저장할 벡터

    // --- 1단계: 10진수 n을 3진수로 변환하여 벡터에 담기 ---
    // n을 3으로 나눈 나머지를 차례대로 저장하면 자연스럽게 "뒤집힌 3진수"가 됩니다.
    // 예: n=45 -> a에는 [0, 0, 2, 1] 순서로 저장됨 (원래 45의 3진수는 1200)
    while(n)
    {
        a.push_back(n%3); // 3으로 나눈 나머지 저장
        n/=3; // 3으로 나눈 몫으로 갱신
    }

    // --- 2단계: 뒤집힌 3진수를 다시 10진수로 변환하기 ---
    // 벡터 a의 마지막 요소부터 거꾸로 순회하며 3의 거듭제곱(sqr)을 곱해줍니다.
    // 벡터 a가 이미 뒤집힌 상태이므로, 마지막 인덱스(a.size()-i-1)부터 계산하면 
    // 결과적으로 '뒤집힌 3진수'를 10진수로 만드는 꼴이 됩니다.
    for(int i=0; i < a.size(); i++)
    {
        // a.size()-i-1은 벡터의 끝에서부터 앞으로 오는 인덱스
        answer += a[a.size()-i-1]*(sqr);
        sqr*=3; // 다음 자릿수를 위해 3을 곱함 (1 -> 3 -> 9 -> 27...)
    }
    
    return answer;
}
